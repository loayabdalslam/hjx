export function runtimeModuleSource(): string {
  return `// HJX runtime v0.2 (Server Driven with Signals)

// Effect tracking
let currentEffect = null;
const effectStack = [];

// Batch management
let isBatching = false;
const batchQueue = new Set();
let batchDepth = 0;

// Signals registry
export const signals = {};

/**
 * Start a batch operation
 */
export function startBatch() {
  isBatching = true;
  batchDepth++;
}

/**
 * End a batch operation
 */
export function endBatch() {
  batchDepth--;
  if (batchDepth === 0) {
    isBatching = false;
    batchQueue.forEach(fn => fn());
    batchQueue.clear();
  }
}

/**
 * Execute a function in a batch
 */
export function batch(fn) {
  startBatch();
  try {
    return fn();
  } finally {
    endBatch();
  }
}

/**
 * Create a signal
 */
export function createSignal(initial) {
  let value = initial;
  const subscribers = new Set();

  const signal = {
    get: () => {
      if (currentEffect) {
        subscribers.add(currentEffect);
      }
      return value;
    },
    set: (newValue) => {
      if (Object.is(value, newValue)) return;
      value = newValue;
      if (isBatching) {
        subscribers.forEach(fn => batchQueue.add(fn));
      } else {
        Promise.resolve().then(() => {
          subscribers.forEach(fn => fn());
        });
      }
    },
    subscribe: (fn) => {
      subscribers.add(fn);
      return () => subscribers.delete(fn);
    }
  };

  return signal;
}

/**
 * Create an effect
 */
export function createEffect(fn) {
  const effect = () => {
    try {
      effectStack.push(effect);
      currentEffect = effect;
      fn();
    } finally {
      effectStack.pop();
      currentEffect = effectStack[effectStack.length - 1] || null;
    }
  };

  effect();
  return () => {};
}

/**
 * Get signal value by key
 */
export function getSignalValue(key) {
  if (key in signals) {
    return signals[key].get();
  }
  const parts = key.split('.');
  let obj = signals;
  for (const part of parts) {
    if (obj && typeof obj === 'object' && part in obj) {
      if (obj[part] && typeof obj[part].get === 'function') {
        return obj[part].get();
      }
      obj = obj[part];
    } else {
      return undefined;
    }
  }
  return obj;
}

/**
 * Create remote store with WebSocket
 */
export function createRemoteStore(wsUrl, initial, rootEl) {
  const state = { ...initial };
  
  // Create signals for all state keys
  function ensureSignal(key) {
    if (!(key in signals)) {
      signals[key] = createSignal(state[key]);
    }
  }

  function connect() {
    const ws = new WebSocket(wsUrl);
    
    ws.onmessage = (msg) => {
      try {
        const data = JSON.parse(msg.data);
        if (data.type === "state") {
          // Initial state - create signals
          Object.assign(state, data.payload);
          for (const key of Object.keys(data.payload)) {
            ensureSignal(key);
            signals[key].set(data.payload[key]);
          }
        } else if (data.type === "patch") {
          if (data.payload._html) {
            rootEl.innerHTML = data.payload._html;
            if (window._hjx_rebind) window._hjx_rebind();
          } else {
            // Apply patch to signals
            for (const [key, value] of Object.entries(data.payload)) {
              if (key.includes(".")) {
                const parts = key.split(".");
                let target = state;
                for (let i = 0; i < parts.length - 1; i++) {
                  if (!target[parts[i]]) target[parts[i]] = {};
                  target = target[parts[i]];
                }
                target[parts[parts.length - 1]] = value;
              } else {
                state[key] = value;
                if (key in signals) {
                  signals[key].set(value);
                } else {
                  ensureSignal(key);
                  signals[key].set(value);
                }
              }
            }
          }
        }
      } catch (e) {
        console.error("WS message error:", e);
      }
    };
    
    ws.onclose = () => {
      console.log("Disconnected. Reconnecting...");
      setTimeout(connect, 1000);
    };
    
    return ws;
  }

  const ws = connect();

  return {
    get: () => state,
    set: (patch) => {
      for (const [key, value] of Object.entries(patch)) {
        if (key in signals) {
          signals[key].set(value);
        } else {
          ensureSignal(key);
          signals[key].set(value);
        }
      }
      if (ws && ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ type: "state_update", payload: patch }));
      }
    },
    sendEvent: (handlerName, payload = {}) => {
      if (ws && ws.readyState === WebSocket.OPEN) {
        ws.send(JSON.stringify({ type: "event", name: handlerName, payload }));
      }
    },
    subscribe: (fn) => {
      // Subscribe to all signals
      const unsubs = [];
      for (const signal of Object.values(signals)) {
        unsubs.push(signal.subscribe(fn));
      }
      return () => unsubs.forEach(u => u());
    }
  };
}

export function mount() {}
`;
}
